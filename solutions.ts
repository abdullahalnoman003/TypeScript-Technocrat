function filterEvenNumbers (num : number[] ): number[] {
    const len = num.length;
    const evenArray:number[] = [];
    for(let i =0; i<len; i++){
        if(num[i] %2 ===0){
            evenArray.push(num[i]);
        }
    }
    return evenArray;
}
